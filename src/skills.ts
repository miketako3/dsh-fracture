/**
 * Skill distillation: repeated successful procedures become markdown.
 *
 * Detection is arithmetic over observations, so it can run on every session
 * close without a model call. The rendered file is deliberately plain: a
 * generated skill that pretends to explain *why* is worse than one that states
 * what was observed and lets the reader judge.
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { Observation } from './observe.js'
import type { Store } from './store.js'

/** A procedure that repeated often enough and never failed. */
export interface SkillCandidate {
  readonly slug: string
  /** Tool names in the order they were used. */
  readonly sequence: readonly string[]
  readonly count: number
  readonly examples: readonly string[]
}

/** Tuning for distillation. */
export interface DistillOptions {
  /** How many successful repetitions make a procedure worth writing down. */
  readonly minRepeats: number
  /** Shortest procedure worth naming; one tool is already described by the tool. */
  readonly minLength: number
}

/** Defaults: three clean repetitions of at least two steps. */
export const DEFAULT_DISTILL: DistillOptions = { minRepeats: 3, minLength: 2 }

/** Marker used to recognize files this loop may overwrite. */
export const GENERATED_MARKER = '<!-- generated by dsh-self-harness -->'

/** Filesystem-safe skill slug. */
export function skillSlug(sequence: readonly string[]): string {
  const joined = sequence.join('-').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  const clipped = joined.slice(0, 48).replace(/-+$/, '')
  return `auto-${clipped === '' ? 'procedure' : clipped}`
}

/** Whether one observation was a clean success. */
function clean(observation: Observation): boolean {
  return observation.failures.length === 0 && !observation.corrected
}

/**
 * Find procedures that repeated and never failed.
 * @param observations - turns from one or more sessions, oldest first.
 * @param options - thresholds; omitted fields use the defaults.
 * @returns candidates, most frequent first.
 */
export function skillCandidates(observations: readonly Observation[], options: Partial<DistillOptions> = {}): SkillCandidate[] {
  const config: DistillOptions = { ...DEFAULT_DISTILL, ...options }
  const groups = new Map<string, { sequence: string[]; count: number; examples: string[] }>()

  for (const observation of observations) {
    if (!clean(observation)) continue
    if (observation.sequence.length < config.minLength) continue
    const key = observation.sequence.join('>')
    const group = groups.get(key) ?? { sequence: [...observation.sequence], count: 0, examples: [] }
    group.count += 1
    const task = observation.task.trim()
    if (task !== '' && !group.examples.includes(task) && group.examples.length < 3) group.examples.push(task)
    groups.set(key, group)
  }

  return [...groups.values()]
    .filter(group => group.count >= config.minRepeats)
    .sort((left, right) => right.count - left.count)
    .map(group => ({
      slug: skillSlug(group.sequence),
      sequence: group.sequence,
      count: group.count,
      examples: group.examples,
    }))
}

/** Render one candidate as a SKILL.md file. */
export function renderSkill(candidate: SkillCandidate, refined?: { name?: string; description?: string; body?: string }): string {
  const name = refined?.name ?? candidate.slug
  const description = refined?.description
    ?? `${candidate.sequence.join(' then ')}: observed ${String(candidate.count)} times with no tool failure.`
  const steps = candidate.sequence.map((tool, index) => `${String(index + 1)}. \`${tool}\``)
  const body = refined?.body ?? [
    '## When this applies',
    '',
    `Work that starts with \`${candidate.sequence[0] ?? 'a tool'}\` and ends at \`${candidate.sequence.at(-1) ?? 'a tool'}\` followed this order without a single tool error.`,
    '',
    '## Order',
    '',
    ...steps,
    '',
    '## Seen on',
    '',
    ...(candidate.examples.length === 0 ? ['- (no task text was recorded)'] : candidate.examples.map(task => `- ${task}`)),
    '',
    '## Caveat',
    '',
    'This file was distilled from counts, not from understanding. If a step exists because of a project convention, say so here before relying on it.',
  ].join('\n')

  return [
    '---',
    `name: ${name}`,
    `description: ${description}`,
    '---',
    '',
    GENERATED_MARKER,
    '',
    body.trimEnd(),
    '',
  ].join('\n')
}

/** One skill file on disk. */
export interface StoredSkill {
  readonly slug: string
  readonly name: string
  readonly description: string
  /** Full file text, so the skill can be registered without a second read. */
  readonly content: string
  readonly path: string
  readonly generated: boolean
}

/** Read the frontmatter of a skill file without a YAML dependency. */
function frontmatter(text: string): { name?: string; description?: string } {
  if (!text.startsWith('---')) return {}
  const end = text.indexOf('\n---', 3)
  if (end === -1) return {}
  const block = text.slice(3, end)
  const fields: { name?: string; description?: string } = {}
  for (const line of block.split('\n')) {
    const match = /^(name|description)\s*:\s*(.+)$/.exec(line.trim())
    if (match === null) continue
    const key = match[1] as 'name' | 'description'
    const value = match[2]
    if (value === undefined) continue
    fields[key] = value.replace(/^["']|["']$/g, '').trim()
  }
  return fields
}

/** List skills in the loop's own skills directory. */
export async function listSkills(store: Store): Promise<StoredSkill[]> {
  let entries
  try {
    entries = await readdir(store.skillsDir, { withFileTypes: true })
  } catch {
    return []
  }
  const skills: StoredSkill[] = []
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const path = join(store.skillsDir, entry.name, 'SKILL.md')
    try {
      const text = await readFile(path, 'utf8')
      const fields = frontmatter(text)
      skills.push({
        slug: entry.name,
        name: fields.name ?? entry.name,
        description: fields.description ?? '',
        content: text,
        path,
        generated: text.includes(GENERATED_MARKER),
      })
    } catch {
      continue
    }
  }
  return skills.sort((left, right) => left.slug.localeCompare(right.slug))
}

/**
 * Write one skill file, never clobbering a hand-written one.
 * @returns the path when written, or undefined when the name is taken by a hand-written skill.
 */
export async function writeSkill(store: Store, slug: string, text: string): Promise<string | undefined> {
  const dir = join(store.skillsDir, slug)
  const path = join(dir, 'SKILL.md')
  try {
    const existing = await readFile(path, 'utf8')
    if (!existing.includes(GENERATED_MARKER)) return undefined
  } catch {
    // Not there yet.
  }
  await mkdir(dir, { recursive: true })
  await writeFile(path, text, 'utf8')
  return path
}
